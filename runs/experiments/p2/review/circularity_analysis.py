"""Analysis: Circularity between distractor_flip_rate metric and distractor_geometry augmentation.

The concern: Both the metric (_composite_left_hand) and the augmentation (_inter_hand_raw)
use the EXACT SAME formulas to recompute inter_hand geometry:
- inter_hand_vec = left_palm - right_palm
- hand_contact = exp(-8.0 * d^2) where d is distances between hand points

If they share the exact formula, does this create a circular advantage for distractor_geometry?
"""

def analyze_circularity():
    print("CIRCULARITY ANALYSIS")
    print("=" * 70)
    print()
    print("Metric (_composite_left_hand in diagnostics.py):")
    print("  - Composites left hand from donor into target clip")
    print("  - Recomputes inter_hand_vec = lp[:, 0] - rp[:, 0]")
    print("  - Recomputes hand_contact = exp(-8.0 * d^2)")
    print()
    print("Augmentation (_inter_hand_raw + add_distractor_hand_features in training.py):")
    print("  - Adds distractor hand to training samples")
    print("  - Recomputes inter_hand_vec = lp[..., 0, :] - rp[..., 0, :]")
    print("  - Recomputes hand_contact = exp(-8.0 * d^2)")
    print()
    print("SHARED FORMULA: Both use identical geometry recomputation!")
    print()
    print("Is this circular?")
    print("-" * 70)
    print()
    print("PARTIAL circularity: The augmentation and metric share the formula,")
    print("BUT this is not necessarily invalid because:")
    print()
    print("1. The formula MATCHES REAL EXTRACTION:")
    print("   extract.py:_inter_hand_geometry() uses the same exp(-8*d^2) formula.")
    print("   So both metric and augmentation are replicating what ACTUALLY HAPPENS")
    print("   when MediaPipe detects two hands in a real video frame.")
    print()
    print("2. The metric tests on HELD-OUT validation samples:")
    print("   - Targets are from validation fold (not seen during training)")
    print("   - Donors are ALSO from validation fold (same fold as targets)")
    print("   - So the metric is NOT testing on augmented training data")
    print()
    print("3. The improvement is NOT trivial:")
    print("   S1 -> S4b shows same_height flip drops from 0.115 to 0.026")
    print("   This means the model learned to be MORE ROBUST to distractor hands,")
    print("   not just to memorize the specific compositing formula.")
    print()
    print("HOWEVER, there IS a concern:")
    print("-" * 70)
    print()
    print("The metric donors come from the SAME VALIDATION FOLD as targets.")
    print("This is not leakage (they're both val), but it means:")
    print("  - If the donor hand geometry has peculiarities from that fold,")
    print("    those peculiarities are ALSO in the training data from other folds")
    print("  - The model may have seen similar inter-hand geometries during training")
    print()
    print("A STRONGER test would use:")
    print("  1. Donors from a DIFFERENT fold (or held-out set)")
    print("  2. Or donors from a different data source entirely")
    print("  3. Or test with VARIED geometry formulas (e.g., different decay rates)")
    print()
    print("VERDICT:")
    print("=" * 70)
    print("The metric is NOT strictly circular (validation data is held out),")
    print("but there is PARTIAL circularity in that:")
    print("  - Same geometry formula used in both aug and metric")
    print("  - Donors and targets are from the same cross-validation splits")
    print()
    print("The gain (0.115 -> 0.026 flip rate) is LIKELY REAL but:")
    print("  - May be somewhat inflated due to formula match")
    print("  - Should be verified on independent test data or with varied compositing")
    print()
    print("Recommendation:")
    print("  Accept the improvement as directionally correct, but note the caveat.")
    print("  For final validation, test on completely held-out data with varied")
    print("  distractor hand positions/geometries.")

if __name__ == "__main__":
    analyze_circularity()
